from __future__ import annotations

# 「二次判断」节点：只看本轮输入里有没有医学信息 / 地点 / 时间。
HAS_SIGNAL_PROMPT = """请分析用户输入的内容：{{query}}

判断标准：
1. 是否包含**医学信息**（疾病、症状、药物、治疗、处方、模板等）
2. 是否包含**地点**
3. 是否包含**时间**

输出格式：
- 如果包含上述**任意一项**，输出：{"has_medical_location_time": true}
- 如果**一项都不包含**，输出：{"has_medical_location_time": false}

只输出JSON，不要其他解释。"""

# 「LLM 4」节点：结构化抽取七个字段（疾病 / 机器人类型 / 训练模式 / 判断依据 /
# 地点 / 时间 / 量表），并对疾病做「仅限康复」的受控推断。
EXTRACT_PROMPT = """你是医疗信息结构化抽取与疾病推断助手。你的任务是基于用户本轮输入 {{query}} 及问诊提取内容 {{talk}} 中出现的医学相关信息，结合临床常识，对可能涉及的疾病进行受控推断，同时提取地点、时间信息，并以结构化 JSON 形式输出。

## 疾病推断范围强制限定规则
仅允许推断【与康复医学直接相关的疾病类型】，包括但不限于：
- 神经系统疾病：脑卒中、脑外伤、脊髓损伤、帕金森病、阿兹海默症等；
- 骨科与运动系统疾病：骨折术后、关节置换术后、颈肩腰腿痛、运动损伤、骨质疏松症、膝关节骨性关节炎等；
- 老年功能障碍：肌力下降、平衡障碍、步态异常等；
- 其他明确需要康复训练的功能障碍性疾病。

若对话中仅涉及与康复无关的普通疾病或症状（如感冒、发烧、咳嗽、腹泻、胃炎、皮肤病等），必须视为“无有效康复疾病”，疾病字段必须为 null。
若对话中同时包含康复相关疾病和非康复相关疾病，只保留康复相关疾病输出，其他疾病一律忽略。

## 疾病字段规则
- 当输入或提取内容中出现明确的【康复相关诊断名称】（如“脑卒中”“骨折术后”），直接填写该疾病。
- 仅输入一个康复相关疾病名称（如“脑卒中”“脊髓损伤”“骨折术后”）时，即视为“出现明确诊断名称”，疾病字段直接填写该名称，不得触发兜底规则。
- 当未出现明确诊断，但存在指向性的康复相关症状或功能障碍时，允许基于医学常识推断 1–3 种最可能的康复相关疾病，用数组格式，如 ["脑卒中","脊髓损伤"]。
- 若仅涉及非康复相关疾病或症状，或信息不足以指向康复疾病，疾病必须为 null。

## 强制兜底规则
仅当 {{query}} 与 {{talk}} 均为空、或完全不含任何有意义文字时，才输出以下兜底 JSON。只要出现任何疾病名、症状、部位、功能障碍或时间词，一律走正常推断，禁止使用兜底：
{"疾病":null,"机器人类型":null,"训练模式":null,"疾病判断依据":null,"地点":null,"时间":null,"量表":null}

## 机器人类型规则
- 若疾病为 null 或非康复相关疾病：机器人类型为 null。
- 若疾病为认知障碍或精神心理类疾病：机器人类型为 null（此类疾病不做肢体机器人训练）。
- 若疾病为其他有效康复疾病：必须给出机器人类型，不允许为空：
  - 涉及行走、站立、下肢活动、步态异常、平衡障碍 → “下肢机器人”；
  - 涉及上肢活动、手功能、抓握或精细动作障碍 → “上肢机器人”；
  - 无法从症状判断上/下肢时，按疾病默认：脑卒中、脑外伤、脊髓损伤、颈肩腰腿痛、膝关节骨性关节炎 → “下肢机器人”；仅当明确涉及手功能、抓握或精细动作 → “上肢机器人”。

## 训练模式规则
- 仅当机器人类型非空时填写；机器人类型为 null 时训练模式为 null。
- 下肢机器人可填写（一种或多种）：“行走游戏”“坐站游戏”“平衡游戏”“平衡评估”。
- 上肢机器人仅允许填写：“单臂游戏”。

## 疾病判断依据规则
- 必须为对象类型：key 为疾病名称，value 为基于对话内容的自然语言判断理由；理由需明确对应症状或表现，且不少于 7 个汉字。
- 即使只有一个疾病也必须使用对象格式。
- 若疾病为 null，则本字段必须为 null。

## 地点字段规则
提取患者或对话中出现的国家、省份、城市、医疗机构名称或具体地区；仅当明确提及时提取，未出现时必须为 null。

## 时间字段规则
规范化提取对话中出现的所有时间信息，包括绝对时间（日期、月份、年份）、相对时间（今天、明天、本周等）、时间段（上午、下午、晚上、周末）、节假日等。
- 若为相对时间，需基于 {{today}} 计算实际日期。
- 时间段处理：只有时间段如“下午”；日期+时间段为 YYYY-MM-DD 时间段。
- 若出现多个时间，以 {{query}} 中时间为优先，仅返回一个。
- 若无明确时间信息则为 null。

## 量表字段规则
根据推断出的疾病类型，选择一个最适合该疾病的康复或评估量表，可选量表仅限：
AD8认知障碍自评表、ADL量表-Barthel指数、ADL日常生活能力量表、Beck抑郁量表、GAD-7广泛性焦虑量表、Rivermead行为记忆量表记录表、汉密尔顿抑郁量表、简易认知状态评价量表、简易智力状态评估表、老年人认知功能筛查量表、蒙特利尔认知评估量表记录表、认知障碍分级评定表。

- 若疾病属于认知障碍或精神心理类疾病：量表必填（选对应认知/情绪量表），机器人类型与训练模式均为 null。
- 若疾病为非认知/精神类康复疾病：按疾病类型选择最适合的一项量表。
- 若疾病为 null：量表必须为 null。

## 强制一致性规则
- 疾病 = null → 机器人类型、训练模式、疾病判断依据、量表均为 null。
- 疾病 ≠ null 且为运动/神经康复疾病 → 机器人类型、训练模式必填。
- 疾病 ≠ null 且为认知/精神类疾病 → 机器人类型、训练模式均为 null，量表必填。
- 疾病为非康复疾病 → 按“无医学相关信息”处理，全部为 null。

## 输出规则
仅输出包含以下字段的严格合法 JSON 对象，不得包含任何解释、说明、示例或多余字符。字段顺序严格为：疾病、机器人类型、训练模式、疾病判断依据、地点、时间、量表。

输出示例（仅为格式说明）：
{"疾病":"...","机器人类型":"...","训练模式":["..."],"疾病判断依据":{...},"地点":"...","时间":"...","量表":"..."}"""


def build_gate_prompt(query: str) -> str:
    """二次判断：只把本轮 query 填进去。"""
    return HAS_SIGNAL_PROMPT.replace("{{query}}", query)


def build_extract_prompt(query: str, talk: str, today: str) -> str:
    """结构化抽取：query + 累计对话 + 今天日期。"""
    return (
        EXTRACT_PROMPT.replace("{{query}}", query)
        .replace("{{talk}}", talk)
        .replace("{{today}}", today)
    )


# 「单疾病输出 / 多疾病处方」节点：按距离从候选机构里挑最近的三个。
LOCATION_PROMPT = """您将收到一个固定地点{{location}}和一个包含多个地点的列表{{tenants}}中的 TenantName。请按照以下步骤操作：
检查固定地点
如果固定地点{{location}}为空或不存在或为null，则直接输出 null 并结束。
解析输入
如果固定地点{{location}}存在且不为null，识别列表中的每个地点。
计算距离
计算每个列表地点{{tenants}}与固定地点{{location}}之间的距离，单位为公里。
筛选最近地点
找出距离固定地点{{location}}最近的三个地点，距离由近到远给出。
输出
如果有最近地点，则仅输出地点名称；
输出示例（纯文本）："""


def build_location_prompt(location: str, tenants: list[str]) -> str:
    """机构筛选：填固定地点与候选机构列表（用顿号拼接，便于模型逐个识别）。"""
    return LOCATION_PROMPT.replace("{{location}}", location).replace(
        "{{tenants}}", "、".join(tenants)
    )
